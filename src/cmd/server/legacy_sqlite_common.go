package main

import (
	"encoding/json"
	"fmt"
	"hash/fnv"
	"strings"
)

const legacySQLiteSchemaVersion = 1

type legacySQLiteStateMeta struct {
	ServerVersion     int64  `json:"serverVersion"`
	RestoreGeneration int64  `json:"restoreGeneration,omitempty"`
	RestoreID         string `json:"restoreId,omitempty"`
	RestoredAt        string `json:"restoredAt,omitempty"`
	UpdatedAt         string `json:"updatedAt"`
	InstallationID    string `json:"installationId"`
}

func legacySQLiteMetaFromState(st legacyState) legacySQLiteStateMeta {
	return legacySQLiteStateMeta{
		ServerVersion: st.ServerVersion, RestoreGeneration: st.RestoreGeneration,
		RestoreID: st.RestoreID, RestoredAt: st.RestoredAt, UpdatedAt: st.UpdatedAt,
		InstallationID: st.InstallationID,
	}
}

func legacySQLiteApplyMeta(st *legacyState, meta legacySQLiteStateMeta) {
	if st == nil {
		return
	}
	st.ServerVersion = meta.ServerVersion
	st.RestoreGeneration = meta.RestoreGeneration
	st.RestoreID = meta.RestoreID
	st.RestoredAt = meta.RestoredAt
	st.UpdatedAt = meta.UpdatedAt
	st.InstallationID = meta.InstallationID
}

// legacyFilesSignature is deliberately cheap. It avoids hashing multi-megabyte
// base64 payloads on every notification/metadata save while still detecting the
// file mutations generated by SGL (new slice, id/size/timestamps or payload size).
func legacyFilesSignature(files []any) string {
	h := fnv.New64a()
	for i, raw := range files {
		m := legacyMap(raw)
		data := fmt.Sprint(m["dataUrl"])
		if data == "<nil>" {
			data = ""
		}
		prefix, suffix := data, data
		if len(prefix) > 32 {
			prefix = prefix[:32]
		}
		if len(suffix) > 32 {
			suffix = suffix[len(suffix)-32:]
		}
		_, _ = fmt.Fprintf(h, "%d|%s|%s|%s|%s|%s|%v|%s|%s|%d|%s|%s\n",
			i, strings.TrimSpace(fmt.Sprint(m["id"])), strings.TrimSpace(fmt.Sprint(m["ownerId"])),
			strings.TrimSpace(fmt.Sprint(m["kind"])), strings.TrimSpace(fmt.Sprint(m["name"])),
			strings.TrimSpace(fmt.Sprint(m["type"])), m["size"], strings.TrimSpace(fmt.Sprint(m["createdAt"])),
			strings.TrimSpace(fmt.Sprint(m["updatedAt"])), len(data), prefix, suffix)
	}
	return fmt.Sprintf("%016x:%d", h.Sum64(), len(files))
}

func legacySQLiteEncode(v any) ([]byte, error) {
	return json.Marshal(v)
}

func legacySQLiteDecode(data []byte, out any) error {
	if len(data) == 0 {
		return nil
	}
	return json.Unmarshal(data, out)
}
